-- 小羊長大日記 — Supabase 版資料表（放在自己的 lamb schema，不會動到專案裡其他 App 的資料）
-- 欄位和 PythonAnywhere 版的 SQLite 一樣；時間都存成台灣時間字串 "YYYY-MM-DDTHH:MM:SS"
create schema if not exists lamb;

create table lamb.teams (
  id         integer generated by default as identity primary key,
  name       text not null,
  avatar     text not null,
  score      integer not null default 0,
  created_at text not null
);
create table lamb.users (
  id         integer generated by default as identity primary key,
  phone      text not null unique,
  name       text not null,
  team_id    integer references lamb.teams(id),
  created_at text not null
);
create table lamb.sessions (
  token      text primary key,
  user_id    integer not null references lamb.users(id),
  created_at text not null
);
create table lamb.checkins (
  id         integer generated by default as identity primary key,
  user_id    integer not null references lamb.users(id),
  team_id    integer not null references lamb.teams(id),
  activity   text not null,
  day        text not null,
  points     integer not null,
  created_at text not null,
  unique (user_id, activity, day)
);
-- status：pending 等待中、done 已組隊、declined 被拒絕、voided 有人已加入別組、cancelled 邀請人取消、closed 邀請人已讀
create table lamb.invites (
  id         integer generated by default as identity primary key,
  inviter_id integer not null references lamb.users(id),
  team_name  text not null,
  avatar     text not null,
  status     text not null,
  note       text not null default '',
  created_at text not null
);
create table lamb.messages (
  id         integer generated by default as identity primary key,
  team_id    integer not null references lamb.teams(id),
  user_id    integer not null references lamb.users(id),
  body       text not null,
  created_at text not null
);
create index idx_messages_team on lamb.messages (team_id, id);
create table lamb.missions (
  id         integer generated by default as identity primary key,
  title      text not null,
  created_at text not null,
  ends_at    text not null,
  status     text not null default 'active'
);
create table lamb.mission_done (
  mission_id integer not null references lamb.missions(id),
  user_id    integer not null references lamb.users(id),
  done_at    text not null,
  primary key (mission_id, user_id)
);
create table lamb.tickets (
  id         integer generated by default as identity primary key,
  team_id    integer not null references lamb.teams(id),
  mission_id integer not null references lamb.missions(id),
  created_at text not null,
  used_at    text,
  prize      text,
  unique (team_id, mission_id)
);
create table lamb.team_prizes (
  team_id    integer not null references lamb.teams(id),
  prize      text not null,
  created_at text not null,
  primary key (team_id, prize)
);
create table lamb.land_days (
  user_id    integer not null references lamb.users(id),
  day        text not null,
  verse      text not null default '',
  items      text not null default '[]',
  updated_at text not null,
  primary key (user_id, day)
);
create table lamb.user_plants (
  user_id    integer not null references lamb.users(id),
  day        text not null,
  plant      text not null,
  created_at text not null,
  primary key (user_id, day)
);
create table lamb.land_pings (
  user_id    integer not null references lamb.users(id),
  day        text not null,
  idx        integer not null,
  primary key (user_id, day, idx)
);
create table lamb.chat_reads (
  user_id    integer primary key references lamb.users(id),
  last_id    integer not null default 0
);
create table lamb.push_subs (
  endpoint   text primary key,
  user_id    integer not null references lamb.users(id),
  p256dh     text not null,
  auth       text not null,
  created_at text not null
);
create table lamb.invite_members (
  invite_id  integer not null references lamb.invites(id),
  user_id    integer not null references lamb.users(id),
  pos        integer not null,
  accepted   integer not null default 0,
  primary key (invite_id, user_id)
);
-- 推播金鑰等設定（取代 push_keys.json），和後台登入失敗紀錄（防猜密碼）
create table lamb.config (
  key   text primary key,
  value text not null
);
create table lamb.admin_fails (
  ip text not null,
  at timestamptz not null default now()
);

-- 只讓 Edge Function（直接連資料庫）讀寫；網頁端的 anon 金鑰完全碰不到
do $$ declare t text; begin
  for t in select tablename from pg_tables where schemaname = 'lamb' loop
    execute format('alter table lamb.%I enable row level security', t);
  end loop;
end $$;
revoke all on schema lamb from anon, authenticated;

