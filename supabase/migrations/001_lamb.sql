select cron.schedule('lamb-land-remind', '*/5 * * * *', $$
  select net.http_post(
    url := 'https://gserdnkovlwfdgcaguqe.supabase.co/functions/v1/lamb',
    headers := '{"Content-Type": "application/json"}'::jsonb,
    body := jsonb_build_object('cron', 'land', 'key', (select value from lamb.config where key = 'cron_key'))
  )
$$);
